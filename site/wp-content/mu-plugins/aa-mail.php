<?php
/**
 * Plugin Name: Annaadhya Mail (must-use)
 * Description: Outbound mail plumbing for the ebook store: branded From address, optional SMTP through wp-config constants (AA_SMTP_*), and HTML email support. Accounts/authentication were removed by design — every book is delivered straight to the customer's email after checkout, so this plugin only cares that those emails actually send.
 * Version:     2.0.0
 * Author:      Annaadhya
 */

if ( ! defined( 'ABSPATH' ) ) exit;

/* ------------------------------------------------------------------------
 * 1. Optional SMTP from wp-config constants (works with any free provider:
 *    Brevo, SendGrid, SES, Gmail...). When no constants are defined,
 *    wp_mail() falls back to the host's built-in PHP mail() — which is
 *    exactly what shared hosting like Hostinger provides out of the box.
 *
 *    define( 'AA_SMTP_HOST', 'smtp-relay.brevo.com' );
 *    define( 'AA_SMTP_PORT', 587 );
 *    define( 'AA_SMTP_USER', '...' );  define( 'AA_SMTP_PASS', '...' );
 *    define( 'AA_SMTP_SECURE', 'tls' );            // '' | 'ssl' | 'tls'
 *    define( 'AA_SMTP_FROM', 'store@yourdomain.com' );
 *    define( 'AA_SMTP_FROM_NAME', 'Annaadhya Ebooks' );
 * ---------------------------------------------------------------------- */

function aa_smtp_configured() {
        return defined( 'AA_SMTP_HOST' ) && AA_SMTP_HOST && defined( 'AA_SMTP_USER' ) && AA_SMTP_USER;
}

/* PHPMailer 7.x (bundled since WP 6.9) validates the From address strictly
 * inside wp_mail()'s own setFrom() call — which happens BEFORE the
 * phpmailer_init hook. A localhost default From (wordpress@localhost) is
 * rejected there and wp_mail() returns false before any SMTP transport is
 * applied. The canonical wp_mail_from filters run earlier, so the branded,
 * valid From from the AA_SMTP_* constants always wins. */
add_filter( 'wp_mail_from', 'aa_wp_mail_from' );
add_filter( 'wp_mail_from_name', 'aa_wp_mail_from_name' );

function aa_wp_mail_from( $from ) {
        if ( aa_smtp_configured() ) {
                return defined( 'AA_SMTP_FROM' ) && AA_SMTP_FROM ? AA_SMTP_FROM : AA_SMTP_USER;
        }
        if ( preg_match( '/@localhost(\.|$)/', (string) $from ) ) {
                // No SMTP configured and WP fell back to wordpress@localhost —
                // use the site domain so receiving servers accept the mail.
                $host = wp_parse_url( home_url(), PHP_URL_HOST );
                if ( $host && 'localhost' !== $host ) { return 'store@' . $host; }
        }
        return $from;
}

function aa_wp_mail_from_name( $name ) {
        if ( aa_smtp_configured() && defined( 'AA_SMTP_FROM_NAME' ) && AA_SMTP_FROM_NAME ) {
                return AA_SMTP_FROM_NAME;
        }
        return $name;
}

add_action( 'phpmailer_init', 'aa_smtp_phpmailer' );

function aa_smtp_phpmailer( $phpmailer ) {
        if ( ! aa_smtp_configured() ) { return; }
        $phpmailer->isSMTP();
        $phpmailer->Host       = AA_SMTP_HOST;
        $phpmailer->Port       = defined( 'AA_SMTP_PORT' ) ? (int) AA_SMTP_PORT : 587;
        $phpmailer->SMTPAuth   = true;
        $phpmailer->Username   = AA_SMTP_USER;
        $phpmailer->Password   = defined( 'AA_SMTP_PASS' ) ? AA_SMTP_PASS : '';
        if ( defined( 'AA_SMTP_SECURE' ) && '' !== AA_SMTP_SECURE ) {
                $phpmailer->SMTPSecure = AA_SMTP_SECURE;
        }
}

/* ------------------------------------------------------------------------
 * 2. HTML mail: let every wp_mail() call pass text/html bodies by adding
 *    the Content-Type header explicitly (AA sends its own headers), and
 *    keep the plain-text alt body generated by PHPMailer.
 * ---------------------------------------------------------------------- */

add_action( 'phpmailer_init', 'aa_mail_html_alt' );

function aa_mail_html_alt( $phpmailer ) {
        // If the message is HTML, make sure a readable plain-text part exists.
        if ( 'text/html' === $phpmailer->ContentType && '' === (string) $phpmailer->AltBody && ! empty( $phpmailer->Body ) ) {
                $phpmailer->AltBody = wp_strip_all_tags( preg_replace( '#<(br|/p|/div|/h[1-6]|/tr)[^>]*>#i', "\n", $phpmailer->Body ) );
        }
}
